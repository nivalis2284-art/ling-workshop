def test_approved_install_fixed_argv_environment_mount_and_pinned_image(
    setup, boundary, manager, packages, monkeypatch
):
    service, runtime, tid, project = setup
    monkeypatch.setenv("OPENAI_API_KEY", "synthetic-host-secret")
    plan = prepare(setup, manager=manager, packages=packages)
    boundary.metadata["id"] = IMAGE_ID  # Execution inspects the pinned ID, never the tag.
    result = approve(service, plan)
    assert result["status"] == "success", result
    create = next(c for c in boundary.calls if c[1] == "create")
    assert create[create.index("--network") + 1] == "bridge"
    assert create[create.index("--entrypoint") + 1] == "/usr/bin/env"
    assert create.count("--mount") == 1 and "--read-only" in create
    mount = create[create.index("--mount") + 1]
    assert f"source={runtime.workspace(tid)}" in mount and "readonly" not in mount
    assert str(project) not in mount
    argv = plan["plan"]["argv"]
    assert create[create.index(IMAGE_ID) + 1 :] == argv[1:]
    assert argv[:2] == ["/usr/bin/env", "-i"]
    assert "HOME=/workspace/.home" in argv and "TMPDIR=/workspace/.tmp" in argv
    assert argv[-len(packages) :] == packages
    if manager == "pip":
        assert argv[argv.index("--target") + 1] == "/workspace/.deps/python"
        assert "--only-binary=:all:" in argv and "-I" in argv and "--upgrade" in argv
        verifier = [c for c in boundary.calls if c[1] == "create"][1]
        assert verifier[verifier.index("--network") + 1] == "none"
        assert "readonly" in verifier[verifier.index("--mount") + 1]
        assert verifier[verifier.index(IMAGE_ID) + 1 :] == plan["plan"]["verification_argv"][1:]
        assert result["result"]["verification"]["exit_code"] == 0
    else:
        assert all(x in argv for x in ("--ignore-scripts", "--no-audit", "--no-fund"))
        assert argv[argv.index("--prefix") + 1] == "/workspace"
        env = plan["plan"]["environment"]
        assert env["NPM_CONFIG_USERCONFIG"] != env["NPM_CONFIG_GLOBALCONFIG"]
        assert env["NPM_CONFIG_GLOBALCONFIG"] == "/workspace/.home/.npm-globalrc"
        assert (runtime.workspace(tid) / ".home/.npm-globalrc").read_bytes() == b""
    assert (runtime.workspace(tid) / ".home").is_dir()
    assert (runtime.workspace(tid) / ".tmp").is_dir()
    assert (project / "main.py").read_text() == "print('original')"
    assert not (project / ".home").exists()
    assert runtime.get(tid)["status"] == "paused"
    assert "synthetic-host-secret" not in repr(boundary.calls)
    assert "must-not-leave-parent" not in repr(result)
    calls = len(boundary.calls)
    assert approve(service, plan) == result
    assert len(boundary.calls) == calls


