@pytest.mark.parametrize("failure", ["cleanup", "timeout", "exception", "truncated"])
def test_verifier_failure_preserves_install_evidence_and_uncertainty(
    setup, boundary, monkeypatch, failure
):
    service, _, tid, _ = setup
    plan = prepare(setup)
    original = boundary.__call__
    creates = 0

    def fail_verification(args, **kwargs):
        nonlocal creates
        if args[1] == "create":
            creates += 1
        if creates == 2:
            if failure == "cleanup" and args[1] == "rm":
                boundary.overrides["rm"] = {"code": 1}
            elif failure == "timeout" and args[1] == "start":
                from test_docker_execution import Process

                boundary.calls.append(args)
                return Process(args, timeout=True)
            elif failure == "exception" and args[1] == "create":
                raise RuntimeError("verifier may have started")
            elif failure == "truncated" and args[1] == "start":
                from test_docker_execution import Process

                boundary.calls.append(args)
                return Process(args, stdout=b"x" * 100_000)
        return original(args, **kwargs)

    monkeypatch.setattr(subprocess, "Popen", fail_verification)
    result = approve(service, plan)
    assert result["status"] == "unknown"
    assert result["error_code"] == "dependency_verification_unconfirmed"
    assert result["result"]["status"] == "success" and result["result"]["exit_code"] == 0
    with pytest.raises(Conflict):
        service.ensure_task_ready(tid)
    with pytest.raises(Conflict):
        prepare(setup, request_id="cannot-repeat-uncertain-effect")
    count = len(boundary.calls)
    assert approve(service, plan) == result
    assert len(boundary.calls) == count


