def prepare(setup, **changes):
    service, _, tid, _ = setup
    return service.prepare(
        **(
            {
                "task_id": tid,
                "manager": "pip",
                "packages": ["requests==2.32.3"],
                "request_id": "dependency-one",
            }
            | changes
        )
    )


def approve(service, plan):
    return asyncio.run(service.approve(plan["id"], intent_hash=plan["intent_hash"]))


