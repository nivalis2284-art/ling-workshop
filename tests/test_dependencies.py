def test_approval_survives_awaiter_cancellation_and_deduplicates_concurrently(setup, boundary):
    service, _, _, _ = setup
    plan = prepare(setup)
    other = prepare(setup, request_id="concurrent-other", packages=["urllib3==2.3.0"])
    entered, release = Event(), Event()
    original = boundary.__call__

    def delayed(args, **kwargs):
        if args[1] == "start":
            entered.set()
            assert release.wait(5)
        return original(args, **kwargs)

    async def run():
        from lingnexus.dependencies import DependencyService

        work = asyncio.create_task(service.approve(plan["id"], intent_hash=plan["intent_hash"]))
        assert await asyncio.to_thread(entered.wait, 5)
        second_service = DependencyService(service.app, service.task_runtime)
        duplicate = await second_service.approve(plan["id"], intent_hash=plan["intent_hash"])
        assert duplicate["status"] == "running"
        with pytest.raises(Conflict):
            await second_service.approve(other["id"], intent_hash=other["intent_hash"])
        work.cancel()
        release.set()
        with pytest.raises(asyncio.CancelledError):
            await work
        for _ in range(200):
            if service.get(plan["id"])["status"] != "running":
                break
            await asyncio.sleep(0.01)
        assert service.get(plan["id"])["status"] == "success"

    with pytest.MonkeyPatch.context() as patch:
        patch.setattr(subprocess, "Popen", delayed)
        try:
            asyncio.run(run())
        finally:
            release.set()
    assert sum(c[1] == "create" for c in boundary.calls) == 2


def test_owner_router_prepare_status_and_exact_decision(setup, boundary):
    from lingnexus.api.dependencies import router

    service, _, tid, _ = setup
    server = FastAPI()
    server.state.dependencies = service
    server.state.owner_token = "owner-token"
    server.state.allowed_origins = {"http://localhost"}
    server.include_router(router)

    @server.exception_handler(DomainError)
    async def error_handler(request, error):
        return JSONResponse(
            {"detail": str(error)},
            status_code=409
            if isinstance(error, Conflict)
            else 404
            if isinstance(error, NotFound)
            else 403,
        )

    async def run():
        async with httpx.AsyncClient(
            transport=httpx.ASGITransport(app=server), base_url="http://localhost"
        ) as browser:
            url = f"/tasks/{tid}/dependencies"
            spec = {"manager": "npm", "packages": ["lodash@4.17.21"], "request_id": "api"}
            headers = {"authorization": "Bearer owner-token"}
            assert (await browser.post(url + "/plan", json=spec)).status_code == 401
            assert (
                await browser.post(
                    url + "/plan", json=spec, headers=headers | {"origin": "https://evil.test"}
                )
            ).status_code == 403
            for extra in (
                {"network_mode": "bridge"},
                {"argv": ["sh"]},
                {"environment": {"SECRET": "x"}},
            ):
                assert (
                    await browser.post(url + "/plan", json=spec | extra, headers=headers)
                ).status_code == 422
            response = await browser.post(url + "/plan", json=spec, headers=headers)
            assert response.status_code == 201, response.text
            plan = response.json()
            detail = url + "/" + plan["id"]
            assert (await browser.get(detail)).status_code == 401
            assert (await browser.get(detail, headers=headers)).json() == plan
            decision = {"decision": "approve", "intent_hash": plan["intent_hash"]}
            assert (await browser.post(detail + "/decision", json=decision)).status_code == 401
            bad = await browser.post(
                detail + "/decision", json=decision | {"intent_hash": "0" * 64}, headers=headers
            )
            assert bad.status_code == 409
            assert (await browser.get(url, headers=headers)).json() == [plan]
            installed = await browser.post(detail + "/decision", json=decision, headers=headers)
            assert installed.status_code == 200 and installed.json()["status"] == "success"
            assert (
                await browser.get(f"/tasks/other/dependencies/{plan['id']}", headers=headers)
            ).status_code == 404

    asyncio.run(run())


